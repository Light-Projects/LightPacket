# Disassembler
# ----------------------------------------------------------------------
def disassemble(instructions: List[Instruction]) -> str:
    lines = []
    for i, insn in enumerate(instructions):
        cls = insn.code & 0x07
        size = insn.code & 0x18
        mode = insn.code & 0xe0
        op = insn.code & 0xf0
        src = insn.code & 0x08

        sz_str = {BPF_W: "w", BPF_H: "h", BPF_B: "b"}.get(size, "")

        if cls == BPF_LD:
            if mode == BPF_IMM:
                text = f"ld #{insn.k}"
            elif mode == BPF_ABS:
                text = f"ld{sz_str} [{insn.k}]"
            elif mode == BPF_IND:
                text = f"ld{sz_str} [x + {insn.k}]"
            elif mode == BPF_MEM:
                text = f"ld M[{insn.k}]"
            elif mode == BPF_LEN:
                text = "ld #len"
            else:
                text = f"ld mode=0x{mode:x}"
        elif cls == BPF_LDX:
            if mode == BPF_MSH:
                text = f"ldxb 4*([{insn.k}]&0xf)"
            elif mode == BPF_IMM:
                text = f"ldx #{insn.k}"
            elif mode == BPF_MEM:
                text = f"ldx M[{insn.k}]"
            elif mode == BPF_LEN:
                text = "ldx #len"
            else:
                text = f"ldx mode=0x{mode:x}"
        elif cls == BPF_ST:
            text = f"st M[{insn.k}]"
        elif cls == BPF_STX:
            text = f"stx M[{insn.k}]"
        elif cls == BPF_ALU:
            alu_str = {
                BPF_ADD: "add", BPF_SUB: "sub", BPF_MUL: "mul", BPF_DIV: "div",
                BPF_MOD: "mod", BPF_AND: "and", BPF_OR: "or", BPF_XOR: "xor",
                BPF_LSH: "lsh", BPF_RSH: "rsh", BPF_NEG: "neg"
            }.get(op, "alu")
            operand = "x" if src == BPF_X else f"#{insn.k}"
            text = f"{alu_str} {operand}"
        elif cls == BPF_JMP:
            if op == BPF_JA:
                text = f"ja {i + 1 + insn.k}"
            else:
                jmp_str = {
                    BPF_JEQ: "jeq", BPF_JGT: "jgt", BPF_JGE: "jge", BPF_JSET: "jset"
                }.get(op, "jmp")
                operand = "x" if src == BPF_X else f"#{hex(int(insn.k))}"
                text = f"{jmp_str} {operand} jt {i + 1 + insn.jt} jf {i + 1 + insn.jf}"
        elif cls == BPF_RET:
            # FIX: original used "not BPF_A" which is always False (BPF_A = 0x10).
            # Correct test is "mode == BPF_A".
            text = "ret a" if mode == BPF_A else f"ret #{hex(int(insn.k))}"
        elif cls == BPF_MISC:
            text = "tax" if op == BPF_TAX else "txa"
        else:
            text = f"raw 0x{insn.code:02x}"

        lines.append(f"({i:03d}) {text}")
    return "\n".join(lines)

def c_str_style(inss: List[Instruction]) -> None:
    # FIX: jt, jf, and k may still be string label names if called before
    # _assemble_and_backpatch resolves them; guard each field so the function
    # doesn't raise TypeError at runtime.
    for ins in inss:
        jt_s = hex(ins.jt) if isinstance(ins.jt, int) else repr(ins.jt)
        jf_s = hex(ins.jf) if isinstance(ins.jf, int) else repr(ins.jf)
        k_s  = hex(ins.k)  if isinstance(ins.k,  int) else repr(ins.k)
        print(f'{{ {hex(ins.code):5},{jt_s:>4},{jf_s:>4},{k_s:>10} }}')

# ----------------------------------------------------------------------
# Emulator
# ----------------------------------------------------------------------
class BpfEmulator:
    """Executes classic BPF bytecode against raw packet bytes."""

    @staticmethod
    def execute(instructions: List[Instruction], packet: bytes) -> int:
        A = 0
        X = 0
        M = [0] * 16
        pc = 0
        pkt_len = len(packet)

        def _read(off: int, sz: int) -> int:
            if off + sz > pkt_len:
                return 0
            if sz == 1:
                return packet[off]
            elif sz == 2:
                return struct.unpack("!H", packet[off:off + 2])[0]
            elif sz == 4:
                return struct.unpack("!I", packet[off:off + 4])[0]
            return 0

        while 0 <= pc < len(instructions):
            insn = instructions[pc]
            cls = insn.code & 0x07
            size = insn.code & 0x18
            mode = insn.code & 0xe0
            op = insn.code & 0xf0
            src = insn.code & 0x08

            sz_bytes = 4 if size == BPF_W else (2 if size == BPF_H else 1)

            if cls == BPF_LD:
                if mode == BPF_IMM:
                    A = insn.k & 0xFFFFFFFF
                elif mode == BPF_ABS:
                    if insn.k + sz_bytes > pkt_len:
                        return 0
                    A = _read(insn.k, sz_bytes)
                elif mode == BPF_IND:
                    if X + insn.k + sz_bytes > pkt_len:
                        return 0
                    A = _read(X + insn.k, sz_bytes)
                elif mode == BPF_MEM:
                    A = M[insn.k] if 0 <= insn.k < 16 else 0
                elif mode == BPF_LEN:
                    A = pkt_len
                pc += 1

            elif cls == BPF_LDX:
                if mode == BPF_IMM:
                    X = insn.k & 0xFFFFFFFF
                elif mode == BPF_MEM:
                    X = M[insn.k] if 0 <= insn.k < 16 else 0
                elif mode == BPF_LEN:
                    X = pkt_len
                elif mode == BPF_MSH:
                    if insn.k >= pkt_len:
                        return 0
                    X = 4 * (packet[insn.k] & 0x0F)
                pc += 1

            elif cls == BPF_ST:
                if 0 <= insn.k < 16:
                    M[insn.k] = A & 0xFFFFFFFF
                pc += 1

            elif cls == BPF_STX:
                if 0 <= insn.k < 16:
                    M[insn.k] = X & 0xFFFFFFFF
                pc += 1

            elif cls == BPF_ALU:
                val = X if src == BPF_X else insn.k
                if op == BPF_ADD:
                    A = (A + val) & 0xFFFFFFFF
                elif op == BPF_SUB:
                    A = (A - val) & 0xFFFFFFFF
                elif op == BPF_MUL:
                    A = (A * val) & 0xFFFFFFFF
                elif op == BPF_DIV:
                    if val == 0:
                        return 0
                    A = (A // val) & 0xFFFFFFFF
                elif op == BPF_MOD:
                    if val == 0:
                        return 0
                    A = (A % val) & 0xFFFFFFFF
                elif op == BPF_AND:
                    A = (A & val) & 0xFFFFFFFF
                elif op == BPF_OR:
                    A = (A | val) & 0xFFFFFFFF
                elif op == BPF_XOR:
                    A = (A ^ val) & 0xFFFFFFFF
                elif op == BPF_LSH:
                    A = (A << (val & 31)) & 0xFFFFFFFF
                elif op == BPF_RSH:
                    A = (A >> (val & 31)) & 0xFFFFFFFF
                elif op == BPF_NEG:
                    A = (-A) & 0xFFFFFFFF
                pc += 1

            elif cls == BPF_JMP:
                if op == BPF_JA:
                    pc += 1 + insn.k
                else:
                    val = X if src == BPF_X else insn.k
                    cond = False
                    if op == BPF_JEQ:
                        cond = (A == val)
                    elif op == BPF_JGT:
                        cond = (A > val)
                    elif op == BPF_JGE:
                        cond = (A >= val)
                    elif op == BPF_JSET:
                        cond = ((A & val) != 0)
                    pc += 1 + (insn.jt if cond else insn.jf)

            elif cls == BPF_RET:
                if mode == BPF_A:
                    return A
                return insn.k

            elif cls == BPF_MISC:
                if op == BPF_TAX:
                    X = A
                elif op == BPF_TXA:
                    A = X
                pc += 1
            else:
                return 0

        return 0