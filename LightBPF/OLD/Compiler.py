# ----------------------------------------------------------------------
@dataclass
class Instruction:
    code: int
    jt: Union[int, str]
    jf: Union[int, str]
    k: Union[int, str]

    def to_bytes(self) -> bytes:
        jt_val = self.jt if isinstance(self.jt, int) else 0
        jf_val = self.jf if isinstance(self.jf, int) else 0
        k_val = self.k if isinstance(self.k, int) else 0
        return struct.pack("HBBI", self.code, jt_val, jf_val, k_val & 0xFFFFFFFF)

    # FIX: previous __repr__ used an invalid format spec and raised ValueError.
    def __repr__(self) -> str:
        k_repr = f"0x{self.k:x}" if isinstance(self.k, int) else str(self.k)
        return (
            f"Instruction(code=0x{self.code:02x}, "
            f"jt={self.jt}, jf={self.jf}, k={k_repr})"
        )


class bpf_insn(ctypes.Structure):
    _fields_ = [
        ("code", ctypes.c_uint16),
        ("jt", ctypes.c_uint8),
        ("jf", ctypes.c_uint8),
        ("k", ctypes.c_uint32),
    ]


class sock_fprog(ctypes.Structure):
    _fields_ = [
        ("len", ctypes.c_ushort),
        ("filter", ctypes.POINTER(bpf_insn)),
    ]


# ----------------------------------------------------------------------
class BpfCompiler:
    """Classic BPF (cBPF) Bytecode Compiler."""

    def __init__(self):
        self.instructions: List[Union[Instruction, str]] = []
        self._label_counter = 0
        self._scratch_counter = 0

    def _new_label(self, prefix: str = "L") -> str:
        self._label_counter += 1
        return f"{prefix}_{self._label_counter}"

    def _emit(self, instr: Instruction):
        self.instructions.append(instr)

    def _emit_label(self, label_name: str):
        self.instructions.append(f"LABEL:{label_name}")

    def compile(self, ast_root: ASTNode) -> List[Instruction]:
        self.instructions = []
        self._label_counter = 0
        self._scratch_counter = 0

        true_label, false_label = "ACCEPT", "REJECT"
        self._compile_bool(ast_root, true_label, false_label)
        return self._assemble_and_backpatch(true_label, false_label)

    @classmethod
    def compile_str(cls, filter_string: str) -> List[Instruction]:
        tokens = BpfLexer(filter_string).tokenize()
        ast = BpfParser(tokens).parse()
        return cls().compile(ast)

    @staticmethod
    def to_bytes(instructions: List[Instruction]) -> bytes:
        return b"".join(instr.to_bytes() for instr in instructions)

    # FIX: keep a reference to the ctypes array alive on the returned sock_fprog
    # so the underlying buffer isn't garbage-collected (previously a dangling ptr).
    @staticmethod
    def to_fprog(instructions: List[Instruction]) -> sock_fprog:
        arr_type = bpf_insn * len(instructions)
        insn_arr = arr_type()
        for idx, instr in enumerate(instructions):
            insn_arr[idx].code = instr.code
            insn_arr[idx].jt = instr.jt if isinstance(instr.jt, int) else 0
            insn_arr[idx].jf = instr.jf if isinstance(instr.jf, int) else 0
            insn_arr[idx].k = (instr.k if isinstance(instr.k, int) else 0) & 0xFFFFFFFF
        fprog = sock_fprog(len(instructions),
                           ctypes.cast(insn_arr, ctypes.POINTER(bpf_insn)))
        # Keep the backing array alive for the lifetime of the sock_fprog.
        fprog._insn_arr = insn_arr  # type: ignore[attr-defined]
        return fprog

    # ------------------------------------------------------------------
    # Boolean Expressions
    # ------------------------------------------------------------------
    def _compile_bool(self, node: ASTNode, true_target: str, false_target: str):
        if isinstance(node, BinaryOpNode):
            if node.op == "and":
                next_label = self._new_label("and")
                self._compile_bool(node.left, next_label, false_target)
                self._emit_label(next_label)
                self._compile_bool(node.right, true_target, false_target)

            elif node.op == "or":
                next_label = self._new_label("or")
                self._compile_bool(node.left, true_target, next_label)
                self._emit_label(next_label)
                self._compile_bool(node.right, true_target, false_target)

            elif node.op in ("==", "!=", ">", ">=", "<", "<="):
                self._compile_comparison(node, true_target, false_target)

            elif node.op == "&":
                self._compile_bitwise_bool(node, true_target, false_target)

            else:
                self._compile_value(node, false_target)
                self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, false_target, true_target, 0))

        elif isinstance(node, UnaryOpNode) and node.op == "not":
            self._compile_bool(node.expr, false_target, true_target)

        elif isinstance(node, ProtocolNode):
            self._compile_protocol(node, true_target, false_target)

        elif isinstance(node, KeywordFilterNode):
            self._compile_keyword(node, true_target, false_target)

        elif isinstance(node, ByteAccessNode):
            self._compile_value(node, false_target)
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, false_target, true_target, 0))

        # FIX: standalone FieldNode is meaningless.  It must appear inside
        # a ByteAccessNode (e.g. tcp[tcpflags]).
        elif isinstance(node, FieldNode):
            raise NotImplementedError(
                f"Standalone pseudo-field '{node.name}' is not valid; "
                f"use it inside a byte access, e.g. tcp[{node.name}]"
            )

        elif isinstance(node, (NumberNode, LengthNode)):
            self._compile_value(node)
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, false_target, true_target, 0))

        else:
            raise NotImplementedError(f"Unsupported boolean AST node: {type(node).__name__}")

    def _compile_bitwise_bool(self, node: BinaryOpNode, true_target: str, false_target: str):
        if isinstance(node.right, NumberNode):
            self._compile_value(node.left, false_target)
            self._emit(Instruction(BPF_JMP | BPF_JSET | BPF_K, true_target, false_target, node.right.value))
        else:
            scratch = self._alloc_scratch()
            self._compile_value(node.right, false_target)
            self._emit(Instruction(BPF_ST, 0, 0, scratch))
            self._compile_value(node.left, false_target)
            self._emit(Instruction(BPF_LDX | BPF_MEM, 0, 0, scratch))
            self._free_scratch()
            self._emit(Instruction(BPF_JMP | BPF_JSET | BPF_X, true_target, false_target, 0))

    def _compile_comparison(self, node: BinaryOpNode, true_target: str, false_target: str):
        # FIX: guard division-by-zero at compile time when divisor is constant.
        # (The original had "and not node.op" which is always False because
        # node.op is never empty — making the check dead code.)
        if (isinstance(node.left, BinaryOpNode) and node.left.op in ("/", "%")
                and isinstance(node.left.right, NumberNode)
                and node.left.right.value == 0):
            raise ValueError("Division by zero in filter expression")

        # Bitmask optimization: expr & MASK != 0 / == 0
        if (isinstance(node.left, BinaryOpNode) and node.left.op == "&" and
                isinstance(node.right, NumberNode) and node.right.value == 0 and
                isinstance(node.left.right, NumberNode)):
            mask = node.left.right.value
            self._compile_value(node.left.left, false_target)
            if node.op in ("!=", ">"):
                self._emit(Instruction(BPF_JMP | BPF_JSET | BPF_K, true_target, false_target, mask))
            elif node.op == "==":
                self._emit(Instruction(BPF_JMP | BPF_JSET | BPF_K, false_target, true_target, mask))
            elif node.op == ">=":
                # A & mask >= 0 is always true in unsigned arithmetic.
                self._emit(Instruction(BPF_JMP | BPF_JA, 0, 0, true_target))
            return

        if isinstance(node.right, NumberNode):
            self._compile_value(node.left, false_target)
            val = node.right.value

            if node.op == "==":
                self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, val))
            elif node.op == "!=":
                self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, false_target, true_target, val))
            elif node.op == ">":
                self._emit(Instruction(BPF_JMP | BPF_JGT | BPF_K, true_target, false_target, val))
            elif node.op == ">=":
                self._emit(Instruction(BPF_JMP | BPF_JGE | BPF_K, true_target, false_target, val))
            elif node.op == "<":
                self._emit(Instruction(BPF_JMP | BPF_JGE | BPF_K, false_target, true_target, val))
            elif node.op == "<=":
                self._emit(Instruction(BPF_JMP | BPF_JGT | BPF_K, false_target, true_target, val))
        else:
            scratch = self._alloc_scratch()
            self._compile_value(node.right,false_target)
            self._emit(Instruction(BPF_ST, 0, 0, scratch))
            self._compile_value(node.left,false_target)
            self._emit(Instruction(BPF_LDX | BPF_MEM, 0, 0, scratch))
            self._free_scratch()

            if node.op == "==":
                self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_X, true_target, false_target, 0))
            elif node.op == "!=":
                self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_X, false_target, true_target, 0))
            elif node.op == ">":
                self._emit(Instruction(BPF_JMP | BPF_JGT | BPF_X, true_target, false_target, 0))
            elif node.op == ">=":
                self._emit(Instruction(BPF_JMP | BPF_JGE | BPF_X, true_target, false_target, 0))
            elif node.op == "<":
                self._emit(Instruction(BPF_JMP | BPF_JGE | BPF_X, false_target, true_target, 0))
            elif node.op == "<=":
                self._emit(Instruction(BPF_JMP | BPF_JGT | BPF_X, false_target, true_target, 0))

    # ------------------------------------------------------------------
    # Protocol Checks
    # ------------------------------------------------------------------
    def _compile_protocol(self, node: ProtocolNode, true_target: str, false_target: str):
        proto_name = node.name.lower()

        if proto_name in ("ether", "link"):
            self._emit(Instruction(BPF_JMP | BPF_JA, 0, 0, true_target))
            return

        if proto_name in ETHER_N:
            self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 12))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target,
                                   ETHERTYPE_MAP.get(proto_name, 0x0800)))
            return

        if proto_name == "vlan":
            self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 12))
            vlan_ok = self._new_label("vlan_ok")
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, vlan_ok, 0x8100))
            self._emit_label(vlan_ok)
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, 0x88a8))
            return

        if proto_name == "mpls":
            self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 12))
            mpls_ok = self._new_label("mpls_ok")
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, mpls_ok, 0x8847))
            self._emit_label(mpls_ok)
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, 0x8848))
            return

        proto_num = None
        if proto_name in BpfLexer.IP_PROTOCOLS:
            proto_num = BpfLexer.IP_PROTOCOLS[proto_name]
        elif node.proto_num is not None:
            proto_num = node.proto_num

        if proto_num is None:
            raise NotImplementedError(f"Unsupported protocol: '{proto_name}'")

        # FIX: icmp6 is IPv6-only; icmp is IPv4-only.  Everything else matches both.
        if proto_name == "icmp6":
            check_ip6 = self._new_label("ip6")
            self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 12))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, check_ip6, false_target, 0x86DD))
            self._emit_label(check_ip6)
            self._emit(Instruction(BPF_LD | BPF_B | BPF_ABS, 0, 0, 20))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, 58))
            return

        if proto_name == "icmp":
            check_ip4 = self._new_label("ip4")
            self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 12))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, check_ip4, false_target, 0x0800))
            self._emit_label(check_ip4)
            self._emit(Instruction(BPF_LD | BPF_B | BPF_ABS, 0, 0, 23))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, 1))
            return

        # Dual-stack: IPv4 (proto byte 23) or IPv6 (next-header byte 20).
        check_ip4 = self._new_label("check_ip4")
        check_ip6 = self._new_label("check_ip6")

        self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 12))
        self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, check_ip4, check_ip6, 0x0800))

        self._emit_label(check_ip4)
        self._emit(Instruction(BPF_LD | BPF_B | BPF_ABS, 0, 0, 23))
        self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, proto_num))

        self._emit_label(check_ip6)
        self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, 0, false_target, 0x86DD))
        self._emit(Instruction(BPF_LD | BPF_B | BPF_ABS, 0, 0, 20))

        check_frag = self._new_label("check_frag")
        frag_ok = self._new_label("frag_ok")
        ip6_ok = self._new_label("ip6_ok")

        self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K,
                               ip6_ok, check_frag, proto_num))

        self._emit_label(check_frag)
        self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K,
                               frag_ok, false_target, 44))

        self._emit_label(frag_ok)
        self._emit(Instruction(BPF_LD | BPF_B | BPF_ABS, 0, 0, 54))
        self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K,
                               ip6_ok, false_target, proto_num))

        self._emit_label(ip6_ok)
        # FIX: the original emitted BPF_LDX here (setting X=40 for transport
        # callers) but never jumped to true_target, so a standalone protocol
        # filter like `proto tcp` would fall off the end and never accept.
        # For _compile_protocol the right epilogue is an unconditional jump to
        # true_target; the transport-layer setup path has its own copy of this
        # logic with the correct LDX + JA epilogue.
        self._emit(Instruction(BPF_JMP | BPF_JA, 0, 0, true_target))

    # ------------------------------------------------------------------
    # Keyword Filters
    # ------------------------------------------------------------------
    def _compile_keyword(self, node: KeywordFilterNode, true_target: str, false_target: str):
        kw = node.keyword

        if kw == "host":
            self._compile_host_filter(node, true_target, false_target)
        elif kw == "net":
            self._compile_net_filter(node, true_target, false_target)
        elif kw == "port":
            self._compile_port_filter(node, true_target, false_target)
        elif kw == "portrange":
            self._compile_portrange_filter(node, true_target, false_target)
        elif kw in ("less", "greater"):
            self._compile_length_filter(node, true_target, false_target)
        elif kw == "broadcast":
            self._compile_broadcast_filter(true_target, false_target)
        elif kw == "multicast":
            self._compile_multicast_filter(true_target, false_target)
        elif kw in ("proto", "protochain"):
            self._compile_proto_filter(node, true_target, false_target)
        elif kw == "vlan":
            self._compile_vlan_filter(node, true_target, false_target)
        elif kw == "mpls":
            self._compile_mpls_filter(node, true_target, false_target)

        # FIX: inbound/outbound cannot be expressed in pure cBPF without socket
        # metadata.  Previously silently matched everything — now raise.
        elif kw in ("inbound", "outbound"):
            raise NotImplementedError(
                f"'{kw}' requires socket metadata and cannot be compiled to cBPF"
            )

        # FIX: gateway was previously compiled as a plain host filter, which is
        # semantically wrong.  libpcap's gateway requires "host is the gateway",
        # i.e. src MAC == host MAC but src IP != host IP.
        elif kw == "gateway":
            raise NotImplementedError(
                "'gateway' is not supported: it requires the host's MAC address, "
                "which is not resolvable at filter-compile time"
            )
        else:
            raise NotImplementedError(f"Unsupported keyword filter: '{kw}'")

    # --- Host Filter ---
    def _compile_host_filter(self, node: KeywordFilterNode, true_target: str, false_target: str):
        vtype = node.value_type
        direction = node.direction

        if vtype == "ipv4":
            ip_int = struct.unpack("!I", socket.inet_aton(node.value))[0]
            self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 12))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, 0, false_target, 0x0800))

            if direction == "src":
                self._emit(Instruction(BPF_LD | BPF_W | BPF_ABS, 0, 0, 26))
                self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, ip_int))
            elif direction == "dst":
                self._emit(Instruction(BPF_LD | BPF_W | BPF_ABS, 0, 0, 30))
                self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, ip_int))
            elif direction == "src and dst":
                check_dst = self._new_label("chk_dst")
                self._emit(Instruction(BPF_LD | BPF_W | BPF_ABS, 0, 0, 26))
                self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, check_dst, false_target, ip_int))
                self._emit_label(check_dst)
                self._emit(Instruction(BPF_LD | BPF_W | BPF_ABS, 0, 0, 30))
                self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, ip_int))
            else:
                chk_dst = self._new_label("chk_dst")
                self._emit(Instruction(BPF_LD | BPF_W | BPF_ABS, 0, 0, 26))
                self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, chk_dst, ip_int))
                self._emit_label(chk_dst)
                self._emit(Instruction(BPF_LD | BPF_W | BPF_ABS, 0, 0, 30))
                self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, ip_int))

        elif vtype == "ipv6":
            words = struct.unpack("!IIII", ipaddress.IPv6Address(node.value).packed)
            self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 12))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, 0, false_target, 0x86DD))

            def _match_ipv6_addr(base_off: int, match_true: str, match_false: str):
                w0_ok = self._new_label("w0_ok")
                w1_ok = self._new_label("w1_ok")
                w2_ok = self._new_label("w2_ok")
                self._emit(Instruction(BPF_LD | BPF_W | BPF_ABS, 0, 0, base_off))
                self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, w0_ok, match_false, words[0]))
                self._emit_label(w0_ok)
                self._emit(Instruction(BPF_LD | BPF_W | BPF_ABS, 0, 0, base_off + 4))
                self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, w1_ok, match_false, words[1]))
                self._emit_label(w1_ok)
                self._emit(Instruction(BPF_LD | BPF_W | BPF_ABS, 0, 0, base_off + 8))
                self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, w2_ok, match_false, words[2]))
                self._emit_label(w2_ok)
                self._emit(Instruction(BPF_LD | BPF_W | BPF_ABS, 0, 0, base_off + 12))
                self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, match_true, match_false, words[3]))

            if direction == "src":
                _match_ipv6_addr(22, true_target, false_target)
            elif direction == "dst":
                _match_ipv6_addr(38, true_target, false_target)
            elif direction == "src and dst":
                chk_dst = self._new_label("chk_dst")
                _match_ipv6_addr(22, chk_dst, false_target)
                self._emit_label(chk_dst)
                _match_ipv6_addr(38, true_target, false_target)
            else:
                chk_dst = self._new_label("chk_dst")
                _match_ipv6_addr(22, true_target, chk_dst)
                self._emit_label(chk_dst)
                _match_ipv6_addr(38, true_target, false_target)

        elif vtype == "mac":
            mac_clean = node.value.replace(":", "").replace("-", "")
            mac_bytes = bytes.fromhex(mac_clean)
            w0 = struct.unpack("!I", mac_bytes[:4])[0]
            h1 = struct.unpack("!H", mac_bytes[4:6])[0]

            def _match_mac(base_off: int, match_true: str, match_false: str):
                part1_ok = self._new_label("mac1")
                self._emit(Instruction(BPF_LD | BPF_W | BPF_ABS, 0, 0, base_off))
                self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, part1_ok, match_false, w0))
                self._emit_label(part1_ok)
                self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, base_off + 4))
                self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, match_true, match_false, h1))

            if direction == "src":
                _match_mac(6, true_target, false_target)
            elif direction == "dst":
                _match_mac(0, true_target, false_target)
            # FIX: 'src and dst' for MAC now requires both.
            elif direction == "src and dst":
                chk_src = self._new_label("chk_src")
                _match_mac(0, chk_src, false_target)
                self._emit_label(chk_src)
                _match_mac(6, true_target, false_target)
            else:
                chk_src = self._new_label("chk_src")
                _match_mac(0, true_target, chk_src)
                self._emit_label(chk_src)
                _match_mac(6, true_target, false_target)

        elif vtype == "name":
            try:
                resolved_ip = socket.gethostbyname(node.value)
            except OSError:
                raise ValueError(f"Could not resolve host name: '{node.value}'")
            # Do not mutate the AST node.
            clone = KeywordFilterNode(
                keyword=node.keyword, value=resolved_ip,
                direction=node.direction, protocol=node.protocol,
                value_type="ipv4", mask=node.mask,
            )
            self._compile_host_filter(clone, true_target, false_target)
        else:
            raise NotImplementedError(f"Unsupported host value type: '{vtype}'")

    # --- Net / Subnet Filter ---
    def _compile_net_filter(self, node: KeywordFilterNode, true_target: str, false_target: str):
        direction = node.direction

        if node.value_type in ("cidr4", "ipv4") or node.mask is not None:
            if node.mask:
                net_str = f"{node.value}/{node.mask}"
                net = ipaddress.IPv4Network(net_str, strict=False)
            elif "/" in str(node.value):
                net = ipaddress.IPv4Network(node.value, strict=False)
            else:
                parts = str(node.value).split(".")
                if len(parts) == 4:
                    # FIX: classful inference.  tcpdump treats net 10.0.0.0 as /8,
                    # net 172.16.0.0 as /16, net 192.168.1.0 as /24.
                    first = int(parts[0])
                    if first < 128:
                        prefix = 8
                    elif first < 192:
                        prefix = 16
                    elif first < 224:
                        prefix = 24
                    else:
                        prefix = 32
                else:
                    prefix = len(parts) * 8
                padded = parts + ["0"] * (4 - len(parts))
                net = ipaddress.IPv4Network(f"{'.'.join(padded)}/{prefix}", strict=False)

            net_int = int(net.network_address)
            mask_int = int(net.netmask)

            self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 12))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, 0, false_target, 0x0800))

            def _match_ipv4_net(offset: int, m_true: str, m_false: str):
                self._emit(Instruction(BPF_LD | BPF_W | BPF_ABS, 0, 0, offset))
                if mask_int != 0xFFFFFFFF:
                    self._emit(Instruction(BPF_ALU | BPF_AND | BPF_K, 0, 0, mask_int))
                self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, m_true, m_false, net_int))

            if direction == "src":
                _match_ipv4_net(26, true_target, false_target)
            elif direction == "dst":
                _match_ipv4_net(30, true_target, false_target)
            elif direction == "src and dst":
                chk_dst = self._new_label("chk_dst")
                _match_ipv4_net(26, chk_dst, false_target)
                self._emit_label(chk_dst)
                _match_ipv4_net(30, true_target, false_target)
            else:
                chk_dst = self._new_label("chk_dst")
                _match_ipv4_net(26, true_target, chk_dst)
                self._emit_label(chk_dst)
                _match_ipv4_net(30, true_target, false_target)

        elif node.value_type == "cidr6":
            net6 = ipaddress.IPv6Network(node.value, strict=False)
            net_words = struct.unpack("!IIII", net6.network_address.packed)
            mask_words = struct.unpack("!IIII", net6.netmask.packed)

            self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 12))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, 0, false_target, 0x86DD))

            def _match_ipv6_net(base_off: int, m_true: str, m_false: str):
                labels = [self._new_label(f"net6_w{i}") for i in range(3)]
                for i in range(4):
                    next_ok = labels[i] if i < 3 else m_true
                    nw = net_words[i]
                    mw = mask_words[i]
                    if mw == 0:
                        self._emit(Instruction(BPF_JMP | BPF_JA, 0, 0, next_ok))
                    else:
                        self._emit(Instruction(BPF_LD | BPF_W | BPF_ABS, 0, 0, base_off + (i * 4)))
                        if mw != 0xFFFFFFFF:
                            self._emit(Instruction(BPF_ALU | BPF_AND | BPF_K, 0, 0, mw))
                        self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, next_ok, m_false, nw))
                    if i < 3:
                        self._emit_label(labels[i])

            if direction == "src":
                _match_ipv6_net(22, true_target, false_target)
            elif direction == "dst":
                _match_ipv6_net(38, true_target, false_target)
            # FIX: 'src and dst' now requires both.
            elif direction == "src and dst":
                chk_dst = self._new_label("chk_dst")
                _match_ipv6_net(22, chk_dst, false_target)
                self._emit_label(chk_dst)
                _match_ipv6_net(38, true_target, false_target)
            else:
                chk_dst = self._new_label("chk_dst")
                _match_ipv6_net(22, true_target, chk_dst)
                self._emit_label(chk_dst)
                _match_ipv6_net(38, true_target, false_target)
        else:
            raise NotImplementedError(f"Unsupported net type: '{node.value_type}'")

    # --- Port / Port Range ---
    def _resolve_port_value(self, val: Any) -> int:
        if isinstance(val, int):
            return val
        sval = str(val).lower()
        if sval.isdigit():
            return int(sval)
        if sval in COMMON_SERVICES:
            return COMMON_SERVICES[sval]
        try:
            return socket.getservbyname(sval)
        except OSError:
            raise ValueError(f"Unknown service or port: '{val}'")

    def _compile_port_filter(self, node: KeywordFilterNode, true_target: str, false_target: str):
        port_num = self._resolve_port_value(node.value)
        direction = node.direction
        proto = node.protocol.lower() if node.protocol else None

        self._setup_transport_layer(proto, false_target)

        if direction == "src":
            self._emit(Instruction(BPF_LD | BPF_H | BPF_IND, 0, 0, 14))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, port_num))
        elif direction == "dst":
            self._emit(Instruction(BPF_LD | BPF_H | BPF_IND, 0, 0, 16))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, port_num))
        elif direction == "src and dst":
            chk_dst = self._new_label("chk_dst")
            self._emit(Instruction(BPF_LD | BPF_H | BPF_IND, 0, 0, 14))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, chk_dst, false_target, port_num))
            self._emit_label(chk_dst)
            self._emit(Instruction(BPF_LD | BPF_H | BPF_IND, 0, 0, 16))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, port_num))
        else:
            chk_dst = self._new_label("chk_dst")
            self._emit(Instruction(BPF_LD | BPF_H | BPF_IND, 0, 0, 14))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, chk_dst, port_num))
            self._emit_label(chk_dst)
            self._emit(Instruction(BPF_LD | BPF_H | BPF_IND, 0, 0, 16))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, port_num))

    def _compile_portrange_filter(self, node: KeywordFilterNode, true_target: str, false_target: str):
        # FIX: coerce lo/hi to int — the parser may deliver them as strings.
        lo, hi = int(node.value[0]), int(node.value[1])
        direction = node.direction
        proto = node.protocol.lower() if node.protocol else None

        self._setup_transport_layer(proto, false_target)

        def _check_range(offset: int, m_true: str, m_false: str):
            chk_hi = self._new_label("chk_hi")
            self._emit(Instruction(BPF_LD | BPF_H | BPF_IND, 0, 0, offset))
            self._emit(Instruction(BPF_JMP | BPF_JGE | BPF_K, chk_hi, m_false, lo))
            self._emit_label(chk_hi)
            self._emit(Instruction(BPF_JMP | BPF_JGT | BPF_K, m_false, m_true, hi))

        if direction == "src":
            _check_range(14, true_target, false_target)
        elif direction == "dst":
            _check_range(16, true_target, false_target)
        # FIX: 'src and dst' previously fell through to the 'or' path.
        elif direction == "src and dst":
            chk_dst = self._new_label("chk_dst")
            _check_range(14, chk_dst, false_target)
            self._emit_label(chk_dst)
            _check_range(16, true_target, false_target)
        else:
            chk_dst = self._new_label("chk_dst")
            _check_range(14, true_target, chk_dst)
            self._emit_label(chk_dst)
            _check_range(16, true_target, false_target)

    # FIX: dual-stack transport-layer setup.  On return, X holds the byte
    # offset from the start of the packet to the transport header:
    #   IPv4: X = IHL  (via BPF_MSH)
    #   IPv6: X = 40   (fixed header, no extension-header traversal)
    # Also validates the IP protocol / next-header, jumping to false_target on
    # mismatch.  This makes `tcp port 80`, `udp port 53`, etc. work over IPv6.
    def _setup_transport_layer(self, proto: Optional[str], false_target: str):
        if proto in _IPV6_ONLY_TRANSPORT:
            proto_num = _TRANSPORT_PROTO_NUM[proto]
            is_ip6 = self._new_label("is_ip6")
            ip6_ok = self._new_label("ip6_ok")
            self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 12))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, is_ip6, false_target, 0x86DD))
            self._emit_label(is_ip6)
            self._emit(Instruction(BPF_LD | BPF_B | BPF_ABS, 0, 0, 20))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, ip6_ok, false_target, proto_num))
            self._emit_label(ip6_ok)
            self._emit(Instruction(BPF_LDX | BPF_IMM, 0, 0, 40))
            return

        if proto in _IPV4_ONLY_TRANSPORT:
            proto_num = _TRANSPORT_PROTO_NUM[proto]
            is_ip4 = self._new_label("is_ip4")
            ip4_ok = self._new_label("ip4_ok")
            self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 12))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, is_ip4, false_target, 0x0800))
            self._emit_label(is_ip4)
            self._emit(Instruction(BPF_LD | BPF_B | BPF_ABS, 0, 0, 23))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, ip4_ok, false_target, proto_num))
            self._emit_label(ip4_ok)
            self._emit(Instruction(BPF_LDX | BPF_B | BPF_MSH, 0, 0, 14))
            return

        # Dual-stack (tcp, udp, sctp, or unspecified → tcp or udp).
        is_ip4 = self._new_label("is_ip4")
        is_ip6 = self._new_label("is_ip6")
        ip4_ok = self._new_label("ip4_ok")
        ip6_ok = self._new_label("ip6_ok")
        transport_ready = self._new_label("transport_ready")

        self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 12))
        self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, is_ip4, is_ip6, 0x0800))

        # ---- IPv4 path ----
        self._emit_label(is_ip4)
        if proto == "tcp":
            self._emit(Instruction(BPF_LD | BPF_B | BPF_ABS, 0, 0, 23))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, ip4_ok, false_target, 6))
        elif proto == "udp":
            self._emit(Instruction(BPF_LD | BPF_B | BPF_ABS, 0, 0, 23))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, ip4_ok, false_target, 17))
        elif proto == "sctp":
            self._emit(Instruction(BPF_LD | BPF_B | BPF_ABS, 0, 0, 23))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, ip4_ok, false_target, 132))
        else:
            is_udp = self._new_label("is_udp")
            self._emit(Instruction(BPF_LD | BPF_B | BPF_ABS, 0, 0, 23))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, ip4_ok, is_udp, 6))
            self._emit_label(is_udp)
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, ip4_ok, false_target, 17))
        self._emit_label(ip4_ok)

        # FIX: reject non-first IPv4 fragments — the port bytes aren't in this fragment.
        first_frag = self._new_label("first_frag")
        self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 20))  # flags + frag off
        self._emit(Instruction(BPF_JMP | BPF_JSET | BPF_K,
                               false_target, first_frag, 0x1FFF))  # non-zero → reject
        self._emit_label(first_frag)

        self._emit(Instruction(BPF_LDX | BPF_B | BPF_MSH, 0, 0, 14))
        self._emit(Instruction(BPF_JMP | BPF_JA, 0, 0, transport_ready))

        # ---- IPv6 path ----
        self._emit_label(is_ip6)
        self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, 0, false_target, 0x86DD))
        if proto == "tcp":
            self._emit(Instruction(BPF_LD | BPF_B | BPF_ABS, 0, 0, 20))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, ip6_ok, false_target, 6))
        elif proto == "udp":
            self._emit(Instruction(BPF_LD | BPF_B | BPF_ABS, 0, 0, 20))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, ip6_ok, false_target, 17))
        elif proto == "sctp":
            self._emit(Instruction(BPF_LD | BPF_B | BPF_ABS, 0, 0, 20))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, ip6_ok, false_target, 132))
        else:
            is_udp6 = self._new_label("is_udp6")
            self._emit(Instruction(BPF_LD | BPF_B | BPF_ABS, 0, 0, 20))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, ip6_ok, is_udp6, 6))
            self._emit_label(is_udp6)
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, ip6_ok, false_target, 17))
        self._emit_label(ip6_ok)
        self._emit(Instruction(BPF_LDX | BPF_IMM, 0, 0, 40))

        self._emit_label(transport_ready)

    # --- Length Filter ---
    def _compile_length_filter(self, node: KeywordFilterNode, true_target: str, false_target: str):
        val = int(node.value)
        self._emit(Instruction(BPF_LD | BPF_W | BPF_LEN, 0, 0, 0))
        if node.keyword == "less":
            self._emit(Instruction(BPF_JMP | BPF_JGT | BPF_K, false_target, true_target, val))
        else:
            self._emit(Instruction(BPF_JMP | BPF_JGE | BPF_K, true_target, false_target, val))

    # --- Broadcast / Multicast ---
    def _compile_broadcast_filter(self, true_target: str, false_target: str):
        part1 = self._new_label("bcast1")
        self._emit(Instruction(BPF_LD | BPF_W | BPF_ABS, 0, 0, 0))
        self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, part1, false_target, 0xFFFFFFFF))
        self._emit_label(part1)
        self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 4))
        self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, 0xFFFF))

    def _compile_multicast_filter(self, true_target: str, false_target: str):
        self._emit(Instruction(BPF_LD | BPF_B | BPF_ABS, 0, 0, 0))
        self._emit(Instruction(BPF_JMP | BPF_JSET | BPF_K, true_target, false_target, 0x01))

    # --- VLAN / MPLS ---
    def _compile_vlan_filter(self, node: KeywordFilterNode, true_target: str, false_target: str):
        vlan_ok = self._new_label("vlan_ok")
        self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 12))
        # FIX: also accept 0x88a8 (802.1ad QinQ).
        self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, vlan_ok, 0, 0x8100))
        self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, vlan_ok, false_target, 0x88a8))
        self._emit_label(vlan_ok)

        if node.value is not None:
            vlan_id = int(node.value)
            self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 14))
            self._emit(Instruction(BPF_ALU | BPF_AND | BPF_K, 0, 0, 0x0FFF))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, vlan_id))
        else:
            self._emit(Instruction(BPF_JMP | BPF_JA, 0, 0, true_target))

    def _compile_mpls_filter(self, node: KeywordFilterNode, true_target: str, false_target: str):
        mpls_ok = self._new_label("mpls_ok")
        self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 12))
        self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, mpls_ok, 0, 0x8847))
        self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, mpls_ok, false_target, 0x8848))
        self._emit_label(mpls_ok)

        if node.value is not None:
            label_val = int(node.value)
            self._emit(Instruction(BPF_LD | BPF_W | BPF_ABS, 0, 0, 14))
            self._emit(Instruction(BPF_ALU | BPF_RSH | BPF_K, 0, 0, 12))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, label_val))
        else:
            self._emit(Instruction(BPF_JMP | BPF_JA, 0, 0, true_target))

    # --- Proto Filter ---
    def _compile_proto_filter(self, node: KeywordFilterNode, true_target: str, false_target: str):
        proto_val = node.value
        num: Optional[int] = None

        # FIX: robust resolution for names vs. numeric literals.
        if isinstance(proto_val, str):
            lv = proto_val.lower()
            if lv in BpfLexer.IP_PROTOCOLS:
                num = BpfLexer.IP_PROTOCOLS[lv]
            elif lv in ETHERTYPE_MAP:
                num = ETHERTYPE_MAP[lv]
            else:
                try:
                    num = int(lv, 0)
                except ValueError:
                    num = None
        elif isinstance(proto_val, int):
            num = proto_val

        if num is None:
            raise ValueError(f"Cannot resolve protocol '{proto_val}'")

        link = (node.protocol or "").lower()
        if link in ("ether", "link"):
            self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 12))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, num))
        elif link in ("ip6", "ipv6"):
            self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 12))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, 0, false_target, 0x86DD))
            self._emit(Instruction(BPF_LD | BPF_B | BPF_ABS, 0, 0, 20))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, num))
        else:
            self._emit(Instruction(BPF_LD | BPF_H | BPF_ABS, 0, 0, 12))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, 0, false_target, 0x0800))
            self._emit(Instruction(BPF_LD | BPF_B | BPF_ABS, 0, 0, 23))
            self._emit(Instruction(BPF_JMP | BPF_JEQ | BPF_K, true_target, false_target, num))

